"""Train a leakage-aware multimodal ensemble for EC prediction.

The ensemble combines class-score vectors from three independently trained
protein-function models:

    annotation + sequence + structure -> multi-head attention -> EC class

For a strict stacking evaluation, the base-model score files supplied for
ensemble training should contain out-of-fold predictions for training samples.
Predictions generated by a base model on samples used to fit that same model
should not be used as ensemble-training features.
"""

from __future__ import annotations

import argparse
import copy
import json
import random
from pathlib import Path

import numpy as np
import pandas as pd
import torch
import torch.nn as nn
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from torch.utils.data import DataLoader, Dataset


class MultimodalDataset(Dataset):
    """Aligned score vectors from three protein-data modalities."""

    def __init__(
        self,
        ids: np.ndarray,
        annotation: np.ndarray,
        sequence: np.ndarray,
        structure: np.ndarray,
        labels: np.ndarray,
    ) -> None:

        self.ids = ids

        self.annotation = torch.tensor(
            annotation,
            dtype=torch.float32,
        )

        self.sequence = torch.tensor(
            sequence,
            dtype=torch.float32,
        )

        self.structure = torch.tensor(
            structure,
            dtype=torch.float32,
        )

        self.labels = torch.tensor(
            labels,
            dtype=torch.long,
        )

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, index: int):

        return (
            self.ids[index],
            self.annotation[index],
            self.sequence[index],
            self.structure[index],
            self.labels[index],
        )


class MultimodalAttentionClassifier(nn.Module):
    """Attention-based fusion of three modality score vectors."""

    def __init__(
        self,
        input_dim: int,
        num_classes: int,
        embed_dim: int = 256,
        num_heads: int = 8,
        ff_dim: int = 512,
        dropout: float = 0.2,
    ) -> None:

        super().__init__()

        self.annotation_projection = nn.Linear(
            input_dim,
            embed_dim,
        )

        self.sequence_projection = nn.Linear(
            input_dim,
            embed_dim,
        )

        self.structure_projection = nn.Linear(
            input_dim,
            embed_dim,
        )

        self.attention = nn.MultiheadAttention(
            embed_dim=embed_dim,
            num_heads=num_heads,
            dropout=dropout,
            batch_first=True,
        )

        self.norm1 = nn.LayerNorm(
            embed_dim
        )

        self.feedforward = nn.Sequential(
            nn.Linear(
                embed_dim,
                ff_dim,
            ),
            nn.ReLU(),
            nn.Dropout(
                dropout
            ),
            nn.Linear(
                ff_dim,
                embed_dim,
            ),
        )

        self.norm2 = nn.LayerNorm(
            embed_dim
        )

        self.dropout = nn.Dropout(
            dropout
        )

        self.classifier = nn.Linear(
            embed_dim,
            num_classes,
        )

    def forward(
        self,
        annotation: torch.Tensor,
        sequence: torch.Tensor,
        structure: torch.Tensor,
    ) -> torch.Tensor:

        modality_tokens = torch.stack(
            [
                self.annotation_projection(
                    annotation
                ),
                self.sequence_projection(
                    sequence
                ),
                self.structure_projection(
                    structure
                ),
            ],
            dim=1,
        )

        attention_output, _ = (
            self.attention(
                modality_tokens,
                modality_tokens,
                modality_tokens,
            )
        )

        hidden = self.norm1(
            modality_tokens
            + self.dropout(
                attention_output
            )
        )

        hidden = self.norm2(
            hidden
            + self.dropout(
                self.feedforward(
                    hidden
                )
            )
        )

        pooled = hidden.mean(
            dim=1
        )

        return self.classifier(
            pooled
        )


def set_seeds(seed: int) -> None:

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(
            seed
        )


def load_scores(
    path: Path,
    prefix: str,
) -> pd.DataFrame:
    """Load modality logits saved in long CSV form."""

    dataframe = pd.read_csv(
        path
    )

    required = {
        "UniProtID",
        "EC",
    }

    missing = required.difference(
        dataframe.columns
    )

    if missing:
        raise ValueError(
            f"{path} is missing: "
            + ", ".join(
                sorted(missing)
            )
        )

    score_columns = [
        column
        for column in dataframe.columns
        if column.startswith(
            "score_"
        )
    ]

    if not score_columns:
        raise ValueError(
            f"{path} contains no "
            "score_* columns."
        )

    renamed = {
        column: (
            f"{prefix}_{column}"
        )
        for column in score_columns
    }

    return dataframe[
        [
            "UniProtID",
            "EC",
            *score_columns,
        ]
    ].rename(
        columns=renamed
    )


def align_modalities(
    annotation_path: Path,
    sequence_path: Path,
    structure_path: Path,
):
    """Join the three modality outputs by UniProt accession."""

    annotation = load_scores(
        annotation_path,
        "annotation",
    )

    sequence = load_scores(
        sequence_path,
        "sequence",
    )

    structure = load_scores(
        structure_path,
        "structure",
    )

    combined = annotation.merge(
        sequence,
        on="UniProtID",
        suffixes=(
            "_annotation",
            "_sequence",
        ),
        how="inner",
    )

    combined = combined.merge(
        structure,
        on="UniProtID",
        how="inner",
    )

    ec_columns = [
        column
        for column in combined.columns
        if column == "EC"
        or column.startswith(
            "EC_"
        )
    ]

    first_ec = combined[
        ec_columns[0]
    ].astype(str)

    for column in ec_columns[1:]:

        matches = (
            combined[column]
            .astype(str)
            .eq(first_ec)
        )

        if not matches.all():
            raise ValueError(
                "EC labels do not agree "
                "across modality files."
            )

    combined["EC"] = first_ec

    combined = combined.drop(
        columns=[
            column
            for column in ec_columns
            if column != "EC"
        ]
    )

    return combined


def score_matrix(
    dataframe: pd.DataFrame,
    prefix: str,
) -> np.ndarray:

    columns = sorted(
        [
            column
            for column in dataframe.columns
            if column.startswith(
                f"{prefix}_score_"
            )
        ],
        key=lambda value: int(
            value.rsplit(
                "_",
                1,
            )[-1]
        ),
    )

    return dataframe[
        columns
    ].to_numpy(
        dtype=np.float32
    )


def make_loader(
    dataframe: pd.DataFrame,
    indices: np.ndarray,
    labels: np.ndarray,
    batch_size: int,
    shuffle: bool,
):

    dataset = MultimodalDataset(
        ids=dataframe[
            "UniProtID"
        ].to_numpy()[indices],
        annotation=score_matrix(
            dataframe,
            "annotation",
        )[indices],
        sequence=score_matrix(
            dataframe,
            "sequence",
        )[indices],
        structure=score_matrix(
            dataframe,
            "structure",
        )[indices],
        labels=labels[
            indices
        ],
    )

    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
    )


def evaluate(
    model,
    loader,
    device,
):

    model.eval()

    ids = []
    logits_list = []
    labels_list = []

    with torch.no_grad():

        for (
            batch_ids,
            annotation,
            sequence,
            structure,
            labels,
        ) in loader:

            annotation = (
                annotation.to(device)
            )

            sequence = (
                sequence.to(device)
            )

            structure = (
                structure.to(device)
            )

            logits = model(
                annotation,
                sequence,
                structure,
            )

            ids.extend(
                list(batch_ids)
            )

            logits_list.append(
                logits.cpu().numpy()
            )

            labels_list.append(
                labels.numpy()
            )

    logits = np.concatenate(
        logits_list,
        axis=0,
    )

    labels = np.concatenate(
        labels_list,
        axis=0,
    )

    predictions = logits.argmax(
        axis=1
    )

    accuracy = accuracy_score(
        labels,
        predictions,
    )

    return (
        accuracy,
        ids,
        logits,
        labels,
    )


def main() -> None:

    parser = argparse.ArgumentParser(
        description=(
            "Train a multimodal "
            "attention ensemble."
        )
    )

    parser.add_argument(
        "--annotation",
        type=Path,
        required=True,
    )

    parser.add_argument(
        "--sequence",
        type=Path,
        required=True,
    )

    parser.add_argument(
        "--structure",
        type=Path,
        required=True,
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "results/ensemble"
        ),
    )

    parser.add_argument(
        "--epochs",
        type=int,
        default=300,
    )

    parser.add_argument(
        "--batch-size",
        type=int,
        default=64,
    )

    parser.add_argument(
        "--learning-rate",
        type=float,
        default=7e-5,
    )

    parser.add_argument(
        "--patience",
        type=int,
        default=30,
    )

    parser.add_argument(
        "--embed-dim",
        type=int,
        default=256,
    )

    parser.add_argument(
        "--num-heads",
        type=int,
        default=8,
    )

    parser.add_argument(
        "--ff-dim",
        type=int,
        default=512,
    )

    parser.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    args = parser.parse_args()

    set_seeds(
        args.seed
    )

    args.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    data = align_modalities(
        args.annotation,
        args.sequence,
        args.structure,
    )

    annotation_scores = (
        score_matrix(
            data,
            "annotation",
        )
    )

    sequence_scores = (
        score_matrix(
            data,
            "sequence",
        )
    )

    structure_scores = (
        score_matrix(
            data,
            "structure",
        )
    )

    dimensions = {
        annotation_scores.shape[1],
        sequence_scores.shape[1],
        structure_scores.shape[1],
    }

    if len(dimensions) != 1:

        raise ValueError(
            "All modality score vectors "
            "must use the same EC-class "
            "vocabulary and dimensionality."
        )

    input_dim = (
        annotation_scores.shape[1]
    )

    label_encoder = (
        LabelEncoder()
    )

    labels = (
        label_encoder.fit_transform(
            data["EC"].astype(str)
        )
    )

    indices = np.arange(
        len(data)
    )

    train_indices, test_indices = (
        train_test_split(
            indices,
            test_size=0.20,
            random_state=0,
        )
    )

    train_indices, val_indices = (
        train_test_split(
            train_indices,
            test_size=0.125,
            random_state=33,
        )
    )

    train_loader = make_loader(
        data,
        train_indices,
        labels,
        args.batch_size,
        True,
    )

    val_loader = make_loader(
        data,
        val_indices,
        labels,
        args.batch_size,
        False,
    )

    test_loader = make_loader(
        data,
        test_indices,
        labels,
        args.batch_size,
        False,
    )

    device = torch.device(
        "cuda"
        if torch.cuda.is_available()
        else "cpu"
    )

    print(
        f"Aligned proteins: "
        f"{len(data)}"
    )

    print(
        f"EC classes: "
        f"{len(label_encoder.classes_)}"
    )

    print(
        f"Base score dimension: "
        f"{input_dim}"
    )

    print(
        f"Train: "
        f"{len(train_indices)}"
    )

    print(
        f"Validation: "
        f"{len(val_indices)}"
    )

    print(
        f"Test: "
        f"{len(test_indices)}"
    )

    model = (
        MultimodalAttentionClassifier(
            input_dim=input_dim,
            num_classes=len(
                label_encoder.classes_
            ),
            embed_dim=args.embed_dim,
            num_heads=args.num_heads,
            ff_dim=args.ff_dim,
        )
        .to(device)
    )

    criterion = (
        nn.CrossEntropyLoss()
    )

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=args.learning_rate,
    )

    best_validation_accuracy = -1.0
    best_state = None
    patience_counter = 0

    history = []

    for epoch in range(
        1,
        args.epochs + 1,
    ):

        model.train()

        total_loss = 0.0
        train_predictions = []
        train_labels = []

        for (
            _,
            annotation,
            sequence,
            structure,
            labels_batch,
        ) in train_loader:

            annotation = (
                annotation.to(device)
            )

            sequence = (
                sequence.to(device)
            )

            structure = (
                structure.to(device)
            )

            labels_batch = (
                labels_batch.to(device)
            )

            optimizer.zero_grad()

            logits = model(
                annotation,
                sequence,
                structure,
            )

            loss = criterion(
                logits,
                labels_batch,
            )

            loss.backward()
            optimizer.step()

            total_loss += (
                loss.item()
            )

            train_predictions.extend(
                logits.argmax(dim=1)
                .detach()
                .cpu()
                .tolist()
            )

            train_labels.extend(
                labels_batch
                .detach()
                .cpu()
                .tolist()
            )

        train_accuracy = (
            accuracy_score(
                train_labels,
                train_predictions,
            )
        )

        (
            validation_accuracy,
            _,
            _,
            _,
        ) = evaluate(
            model,
            val_loader,
            device,
        )

        history.append(
            {
                "epoch": epoch,
                "train_loss": (
                    total_loss
                    / max(
                        len(train_loader),
                        1,
                    )
                ),
                "train_accuracy": float(
                    train_accuracy
                ),
                "validation_accuracy": float(
                    validation_accuracy
                ),
            }
        )

        print(
            f"Epoch {epoch:03d} | "
            f"train_acc="
            f"{train_accuracy:.4f} | "
            f"val_acc="
            f"{validation_accuracy:.4f}"
        )

        if (
            validation_accuracy
            > best_validation_accuracy
        ):

            best_validation_accuracy = (
                validation_accuracy
            )

            best_state = copy.deepcopy(
                model.state_dict()
            )

            patience_counter = 0

        else:

            patience_counter += 1

            if (
                patience_counter
                >= args.patience
            ):

                print(
                    "Early stopping triggered."
                )

                break

    if best_state is None:

        raise RuntimeError(
            "No model checkpoint "
            "was produced."
        )

    model.load_state_dict(
        best_state
    )

    (
        test_accuracy,
        test_ids,
        test_logits,
        test_labels,
    ) = evaluate(
        model,
        test_loader,
        device,
    )

    test_predictions = (
        test_logits.argmax(
            axis=1
        )
    )

    pd.DataFrame(
        {
            "UniProtID": test_ids,
            "True_EC": (
                label_encoder
                .inverse_transform(
                    test_labels
                )
            ),
            "Predicted_EC": (
                label_encoder
                .inverse_transform(
                    test_predictions
                )
            ),
        }
    ).to_csv(
        args.output_dir
        / "test_predictions.csv",
        index=False,
    )

    pd.DataFrame(
        history
    ).to_csv(
        args.output_dir
        / "training_history.csv",
        index=False,
    )

    torch.save(
        best_state,
        args.output_dir
        / "multimodal_attention.pt",
    )

    metrics = {
        "aligned_proteins": len(
            data
        ),
        "num_ec_classes": len(
            label_encoder.classes_
        ),
        "train_records": len(
            train_indices
        ),
        "validation_records": len(
            val_indices
        ),
        "test_records": len(
            test_indices
        ),
        "best_validation_accuracy": float(
            best_validation_accuracy
        ),
        "test_accuracy": float(
            test_accuracy
        ),
        "seed": args.seed,
    }

    (
        args.output_dir
        / "metrics.json"
    ).write_text(
        json.dumps(
            metrics,
            indent=2,
        ),
        encoding="utf-8",
    )

    print(
        f"Held-out test accuracy: "
        f"{test_accuracy:.4f}"
    )


if __name__ == "__main__":
    main()
